// Writes CONTRAST.md from src/styles/tokens.css. Run with `pnpm contrast`.
import { readFileSync, writeFileSync } from 'node:fs'
import {
  BASE_TOKEN,
  checkGamut,
  checkPairs,
  oklchToSrgb,
  parseTokens,
  resolveToken,
  toHex,
} from '../src/styles/contrast.ts'

const root = new URL('../', import.meta.url)
const tokens = parseTokens(readFileSync(new URL('src/styles/tokens.css', root), 'utf8'))
const results = checkPairs(tokens)
const gamut = checkGamut(tokens)
const base = resolveToken(BASE_TOKEN, tokens)

function swatch(token: string): string {
  return `\`${token}\` (${toHex(oklchToSrgb(resolveToken(token, tokens)))})`
}

const failures = results.filter((result) => !result.passes)
const outOfGamut = gamut.filter((result) => !result.inGamut)

const lines = [
  '# Color contrast',
  '',
  '_This file is generated by `pnpm contrast`. Do not edit it by hand._',
  '',
  `Base color: \`${BASE_TOKEN}: oklch(${base.l} ${base.c} ${base.h})\` (${toHex(oklchToSrgb(base))}).`,
  '',
  '## Method',
  '',
  '- Every token in `src/styles/tokens.css` is resolved the way the browser does it: `var()`',
  '  references are followed and each relative `oklch(from …)` formula is evaluated against',
  '  `--color-primary`. The note colors are plain `oklch()` literals.',
  '- Colors are converted OKLCH → OKLab → linear sRGB → sRGB with the OKLab reference matrices.',
  '- The ratio is the WCAG 2.x contrast ratio `(L1 + 0.05) / (L2 + 0.05)` on relative luminance.',
  '- Required: 4.5:1 for text (WCAG 1.4.3), 3:1 for borders, focus rings and other UI parts (1.4.11).',
  '- Ratios are truncated to 2 decimals for display; pass/fail uses the unrounded value.',
  `- Gamut: ${gamut.length - outOfGamut.length} of ${gamut.length} color tokens are inside sRGB, so the browser shows them without gamut mapping.`,
  '',
  `## Results: ${results.length - failures.length} of ${results.length} pairs pass`,
  '',
  '| Foreground | Background | Purpose | Ratio | Required | Result |',
  '| --- | --- | --- | --- | --- | --- |',
  ...results.map(
    (result) =>
      `| ${swatch(result.foreground)} | ${swatch(result.background)} | ${result.purpose} | ${(Math.floor(result.ratio * 100) / 100).toFixed(2)}:1 | ${result.required}:1 | ${result.passes ? 'Pass' : '**Fail**'} |`,
  ),
  '',
]

writeFileSync(new URL('CONTRAST.md', root), lines.join('\n'))
process.stdout.write(
  `CONTRAST.md written: ${results.length - failures.length}/${results.length} pairs pass, ${outOfGamut.length} tokens out of gamut.\n`,
)
if (failures.length > 0 || outOfGamut.length > 0) {
  process.exitCode = 1
}
